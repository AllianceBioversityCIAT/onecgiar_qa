#!/usr/bin/env bash
# Refresh the copy of the AI worker contract (spec assessment/ai-suggestions, T-2).
# Usage: scripts/sync-ai-contract.sh <path to ai-qa-helper>
# Copies contract/schema, contract/examples and production.json, writes
# manifest.json (sha256 per file + the worker commit) and regenerates
# src/ai-suggestions/production.ts from production.json (never edit it by hand;
# the contract test fails when the two differ).
set -euo pipefail
src="${1:?path to ai-qa-helper}"
dst="$(cd "$(dirname "$0")/.." && pwd)/src/ai-suggestions/contract"
rm -rf "$dst/schema" "$dst/examples"
mkdir -p "$dst/schema" "$dst/examples"
cp "$src"/contract/schema/*.json "$dst/schema/"
cp "$src"/contract/examples/*.json "$dst/examples/"
cp "$src"/contract/production.json "$dst/"
commit="$(git -C "$src" rev-parse --short HEAD)"
branch="$(git -C "$src" rev-parse --abbrev-ref HEAD)"
cd "$dst"
{
  printf '{\n  "source": "ai-services/ai-qa-helper",\n  "branch": "%s",\n  "commit": "%s",\n  "files": {\n' "$branch" "$commit"
  first=1
  for f in production.json schema/*.json examples/*.json; do
    [ $first -eq 1 ] || printf ',\n'
    first=0
    printf '    "%s": "%s"' "$f" "$(shasum -a 256 "$f" | cut -d' ' -f1)"
  done
  printf '\n  }\n}\n'
} > manifest.json
node -e '
const fs = require("fs");
const json = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
const out = [
  "// @akili-spec assessment/ai-suggestions",
  "// GENERATED by scripts/sync-ai-contract.sh from contract/production.json. Do not edit.",
  "import type { AiProductionContract } from \"./production-contract.js\";",
  "",
  "export const AI_PRODUCTION: AiProductionContract = " + JSON.stringify(json, null, 2) + ";",
  "",
].join("\n");
fs.writeFileSync(process.argv[2], out);
' "$dst/production.json" "$dst/../production.ts"
(cd "$dst/../../.." && npx --no-install prettier --write src/ai-suggestions/production.ts >/dev/null) || true
echo "contract synced from $branch@$commit"
